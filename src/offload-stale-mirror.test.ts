const execFileAsync = promisify(execFile);
const dirs: string[] = [];
afterEach(() => { for (const dir of dirs.splice(0)) rmSync(dir, { recursive: true, force: true }); });

function temp(): string {
  const dir = mkdtempSync(path.join(tmpdir(), "boat-stale-mirror-"));
  dirs.push(dir);
  return dir;
}

function write(root: string, rel: string, content: string): void {
  const abs = path.join(root, rel);
  mkdirSync(path.dirname(abs), { recursive: true });
  writeFileSync(abs, content);
}

async function runGuestInspectScan(mirror: string, scratch: string): Promise<string> {
  return new Promise<string>((resolve, reject) => {
    const child = spawn("python3", ["-I", "-c", GUEST_INSPECT_SCRIPT], { cwd: scratch });
    const chunks: Buffer[] = [];
    child.stdout.on("data", (chunk: Buffer) => chunks.push(chunk));
    child.stderr.on("data", () => undefined);
    child.on("error", reject);
    child.on("close", (code) => code === 0
      ? resolve(Buffer.concat(chunks).toString("utf8"))
      : reject(new Error(`inspect script exited ${code}`)));
    child.stdin.end(JSON.stringify([mirror, "scan", null, DEFAULT_SYNC_EXCLUDES]));
  });
}

async function collectTwice(plant: (guest: string) => Promise<void> | void) {
  const live = temp();
  const guest = temp();
  write(live, "src/main.rs", "x\n");
  write(live, "Cargo.lock", "v1\n");
  write(guest, "src/main.rs", "x\n");
  write(guest, "Cargo.lock", "v1\n");
  const uploaded = (await captureManifest(live)).manifest;
  await plant(guest);
  const first = await collectAndStage({
    liveRoot: live, uploaded, guest: new LocalGuestStore(), guestDir: guest,
    stagingDir: path.join(temp(), "cmd-1"),
  });
  const previousGuest: Map<string, GuestFileState> | undefined =
    first.scan.truncated ? undefined : first.scan.files;
  const secondStaging = path.join(temp(), "cmd-2");
  const second = await collectAndStage({
    liveRoot: live, uploaded, guest: new LocalGuestStore(), guestDir: guest,
    stagingDir: secondStaging, previousGuest,
  });
  return { live, guest, uploaded, first, second, previousGuest };
}

describe("stale mirror output does not fail later commands", () => {
  it("excluded tool output (.hypothesis, test-results) is clean on both collects with no artifact", async () => {
    const { first, second } = await collectTwice((guest) => {
      write(guest, ".hypothesis/examples/x", "hypothesis state\n");
      write(guest, "test-results/trace.zip", "zip bytes\n");
      write(guest, ".tox/py311/log", "tox\n");
      write(guest, "playwright-report/index.html", "report\n");
      write(guest, "pkg.egg-info/PKG-INFO", "meta\n");
      write(guest, "prof/foo.profraw", "prof\n");
    });
    for (const result of [first, second]) {
      expect(result.state).toBe("clean");
      expect(result.artifactDir).toBeNull();
      expect(result.changedPaths).toEqual([]);
    }
  });

  it("non-excluded guest-only output stages nothing and is gone from the second collect", async () => {
    const { first, second } = await collectTwice((guest) => {
      write(guest, "tool-output/report.txt", "generated by the tool\n");
    });
    // First collect reports it as an unsupported create but keeps no artifact
    // and does not stage: the shim exit stays the command's own.
    expect(first.state).toBe("clean");
    expect(first.artifactDir).toBeNull();
    expect(first.unsupportedPaths).toEqual(["tool-output/report.txt"]);
    // Identical to the previous post-collect scan: not this command's change.
    expect(second.state).toBe("clean");
    expect(second.artifactDir).toBeNull();
    expect(second.changedPaths).toEqual([]);
    expect(second.changes).toEqual([]);
  });

  it("a modified Cargo.lock still stages and maps a clean remote exit to 74", async () => {
    const { first } = await collectTwice((guest) => {
      write(guest, "Cargo.lock", "v1\n# new-dep\n");
    });
    expect(first.state).toBe("staged");
    expect(first.artifactDir).not.toBeNull();
    const exit = exitForTerminal({
      exitCode: 0, signal: null, timedOut: false, cancelled: false, usageRecordId: null,
      syncBack: { state: first.state, changedPaths: first.changedPaths, conflictPaths: [], artifactId: first.artifactDir },
    });
    expect(exit).toBe(74);
  });

  it("a repeated edit to an uploaded file stages again on the second collect", async () => {
    // Push restores uploaded files to the host baseline before every command,
    // so an edit identical to the previous command's is still this command's
    // change: the previous-scan suppression covers guest-only output only.
    const { first, second } = await collectTwice((guest) => {
      write(guest, "Cargo.lock", "v1\n# new-dep\n");
    });
    expect(first.state).toBe("staged");
    expect(second.state).toBe("staged");
    expect(second.artifactDir).not.toBeNull();
    expect(second.changedPaths).toEqual(["Cargo.lock"]);
  });

  it("a repeated delete of an uploaded file is proposed again on the second collect", async () => {
    const { first, second } = await collectTwice((guest) => {
      rmSync(path.join(guest, "Cargo.lock"));
    });
    expect(first.changes).toContainEqual(expect.objectContaining({ path: "Cargo.lock", op: "proposed-delete" }));
    expect(second.state).toBe("staged");
    expect(second.changes).toContainEqual(expect.objectContaining({ path: "Cargo.lock", op: "proposed-delete" }));
  });

  it("a truncated scan never stages phantom deletions of unseen uploaded files", async () => {
    const live = temp();
    const guest = temp();
    write(live, "src/main.rs", "x\n");
    write(live, "Cargo.lock", "v1\n");
    write(guest, "src/main.rs", "x\n");
    write(guest, "Cargo.lock", "v1\n");
    write(guest, "extra-output.log", "noise\n");
    const uploaded = (await captureManifest(live)).manifest;
    const result = await collectAndStage({
      liveRoot: live, uploaded, guest: new LocalGuestStore({ maxScanEntries: 1 }),
      guestDir: guest, stagingDir: path.join(temp(), "cmd-trunc"),
    });
    expect(result.scan.truncated).toBe(true);
    expect(result.truncated).toBe(true);
    expect(result.changes.some((c) => c.op === "proposed-delete")).toBe(false);
    expect(result.state).toBe("clean");
    expect(result.artifactDir).toBeNull();
  });

  it("clean and truncated sync-backs preserve the remote exit code", () => {
    for (const state of ["clean", "truncated"] as const) {
      expect(exitForTerminal({
        exitCode: 0, signal: null, timedOut: false, cancelled: false, usageRecordId: null,
        syncBack: { state, changedPaths: [], conflictPaths: [], artifactId: null },
      })).toBe(0);
    }
  });
});

describe("special files and oversized output never make collect throw", () => {
  it("LocalGuestStore records a FIFO as special and an over-budget file as unhashed", async () => {
    const guest = temp();
    write(guest, "src/main.rs", "x\n");
    write(guest, "big.bin", "0123456789".repeat(100));
    await execFileAsync("mkfifo", [path.join(guest, ".s.PGSQL.5432")]);
    const scan = await new LocalGuestStore({ maxScanBytes: 100 }).scan(guest);
    expect(scan.files.get(".s.PGSQL.5432")).toMatchObject({ special: true, sha256: "" });
    expect(scan.files.get("big.bin")).toMatchObject({ unhashed: true, sha256: "", size: 1000 });
    expect(scan.files.get("src/main.rs")?.sha256).toMatch(/^[0-9a-f]{64}$/);
  });

  it("collectAndStage returns a flagged, truncated result instead of throwing", async () => {
    const live = temp();
    const guest = temp();
    write(live, "src/main.rs", "x\n");
    write(guest, "src/main.rs", "x\n");
    const uploaded = (await captureManifest(live)).manifest;
    write(guest, "video.webm", "0123456789".repeat(100));
    await execFileAsync("mkfifo", [path.join(guest, "pipe")]);
    const result = await collectAndStage({
      liveRoot: live, uploaded, guest: new LocalGuestStore({ maxScanBytes: 100 }),
      guestDir: guest, stagingDir: path.join(temp(), "cmd-fifo"),
    });
    expect(result.state).toBe("clean");
    expect(result.artifactDir).toBeNull();
    expect(result.truncated).toBe(true);
    expect(result.unsupportedPaths.sort()).toEqual(["pipe", "video.webm"]);
    for (const change of result.changes) {
      expect(change.supported).toBe(false);
      expect(change.returnedSha256).toBeNull();
      expect(change.stagedRelPath).toBeNull();
    }
  });

  it("the guest inspect script flags a FIFO and a 300 MiB file instead of raising", async () => {
    const mirror = temp();
    const scratch = temp();
    write(mirror, "keep.txt", "keep\n");
    write(mirror, "huge.bin", "");
    truncateSync(path.join(mirror, "huge.bin"), 300 * 1024 * 1024);
    await execFileAsync("mkfifo", [path.join(mirror, "fifo")]);
    write(mirror, "test-results/trace.zip", "excluded\n");
    const stdout = await runGuestInspectScan(mirror, scratch);
    const scan = validateGuestScan(JSON.parse(stdout));
    expect(scan.files.get("fifo")).toMatchObject({ special: true, sha256: "" });
    expect(scan.files.get("huge.bin")).toMatchObject({ unhashed: true, sha256: "", size: 300 * 1024 * 1024 });
    expect(scan.files.get("keep.txt")?.sha256).toMatch(/^[0-9a-f]{64}$/);
    expect(scan.files.has("test-results/trace.zip")).toBe(false);
  });

  it("the guest inspect script truncates before its JSON outgrows the transport cap", async () => {
    const mirror = temp();
    const scratch = temp();
    // Deep, long names: each scan entry's JSON is ~1 KiB, so the serialized
    // byte budget binds well before the 100k entry limit.
    const deep = path.join(mirror, "d".repeat(250), "e".repeat(250), "f".repeat(250));
    mkdirSync(deep, { recursive: true });
    const total = 14_000;
    for (let i = 0; i < total; i += 1) {
      writeFileSync(path.join(deep, `f${String(i).padStart(200, "0")}`), "");
    }
    const stdout = await runGuestInspectScan(mirror, scratch);
    expect(Buffer.byteLength(stdout)).toBeLessThan(16 * 1024 * 1024);
    const scan = validateGuestScan(JSON.parse(stdout));
    expect(scan.truncated).toBe(true);
    expect(scan.files.size).toBeLessThan(total);
  }, 60_000);

  it("the guest inspect script counts symlink targets against its serialized-size budget", async () => {
    const mirror = temp();
    const scratch = temp();
    // In-root symlinks with near-path-max targets: the target string, not the
    // link name, is what outgrows the transport cap if it is not counted.
    const target = Array.from({ length: 17 }, () => "a".repeat(200)).join("/");
    const total = 5_000;
    for (let i = 0; i < total; i += 1) {
      symlinkSync(target, path.join(mirror, `link-${String(i).padStart(4, "0")}`));
    }
    const stdout = await runGuestInspectScan(mirror, scratch);
    expect(Buffer.byteLength(stdout)).toBeLessThan(16 * 1024 * 1024);
    const scan = validateGuestScan(JSON.parse(stdout));
    expect(scan.truncated).toBe(true);
    expect(scan.files.size).toBeLessThan(total);
  }, 60_000);
});

describe("deterministic inspect failures surface as SyncError", () => {
  function storeWith(response: { exitCode: number | null; timedOut: boolean; signal: string | null }): SshGuestStore {
    const ssh = {
      runStream: async () => ({ stdout: "", stderr: "", ...response }),
      ensureKey: async () => ({ privateKeyPath: "/test/id", publicKey: "test" }),
    };
    return new SshGuestStore({ ssh: ssh as never, session: {} as never });
  }

  it("script exit 1 is SYNC_GUEST_READ; a timed-out transport is not", async () => {
    const refused = await storeWith({ exitCode: 1, timedOut: false, signal: null })
      .scan("/guest/mirror").then(() => null, (caught: unknown) => caught);
    expect(refused).toBeInstanceOf(SyncError);
    expect((refused as SyncError).code).toBe("SYNC_GUEST_READ");
    const lost = await storeWith({ exitCode: null, timedOut: true, signal: null })
      .scan("/guest/mirror").then(() => null, (caught: unknown) => caught);
    expect(lost).toBeInstanceOf(Error);
    expect(lost).not.toBeInstanceOf(SyncError);
  });
});

describe("collect failure after a completed transport", () => {
  let root: string;
  let h: ReturnType<typeof harness>;
  beforeEach(async () => {
    root = await mkdtemp(path.join(process.env.PAPERCLIP_RUN_SCRATCH_DIR ?? tmpdir(), "boat-collect-fail-"));
    h = harness(root);
  });
  afterEach(async () => { h.crash(); await rm(root, { recursive: true, force: true }); });

  it("reports the real exit with a truncated sync-back, marks the mirror suspect, and does not quarantine", async () => {
    const suspect: string[] = [];
    const discarded: string[] = [];
    const sync = {
      push: async () => {},
      collect: async () => { throw Object.assign(new Error("guest scan refused"), { collectDeterministic: true }); },
      stage: async () => {},
      markSuspect: async (_vm: string, cmd: { commandId: string }) => { suspect.push(cmd.commandId); },
      discard: async (_vm: string, cmd: { commandId: string }) => { discarded.push(cmd.commandId); },
    };
    const { executor } = h.openExecutor({
      sync: sync as never,
      runCommand: async (vm, cmd, ...rest: unknown[]) => {
        h.attempts.push({ vm, command: cmd as never, intent: null, identity: rest[0] as never });
        return { exitCode: 0, seconds: 1 };
      },
    });
    const result = await executor.execute(command());
    expect(result).toMatchObject({ status: "completed", exitCode: 0 });
    expect(result).toMatchObject({ syncBack: { state: "truncated", artifactId: null } });
    expect(suspect).toEqual(["command-1"]);
    expect(discarded).toEqual(["command-1"]);
    // The single pool VM was released, not quarantined: a second command runs.
    const second = await executor.execute(command("command-2"));
    expect(second).toMatchObject({ status: "completed", exitCode: 0 });
    expect(h.attempts).toHaveLength(2);
  });
});

describe("artifact root sweep", () => {
  function plantArtifacts(root: string, base: number, count: number): void {
    for (let i = 0; i < count; i += 1) {
      const dir = path.join(root, `command-${i}`);
      mkdirSync(dir);
      const when = new Date(base + i * 1000);
      utimesSync(dir, when, when);
    }
  }

  it("caps retained artifact dirs by count, oldest first, never touching live ones", async () => {
    const root = temp();
    plantArtifacts(root, 1_700_000_000_000, 5);
    const live = new Set([path.join(root, "command-0")]);
    // Every dir is older than the count-eviction horizon, so the cap binds.
    await sweepArtifactRoot(root, 0, live, 2, 1_800_000_000_000);
    expect(readdirSync(root).sort()).toEqual(["command-0", "command-4"]);
    expect(existsSync(path.join(root, "command-0"))).toBe(true);
  });

  it("never count-evicts an artifact a retained result can still name", async () => {
    const root = temp();
    plantArtifacts(root, 1_700_000_000_000, 5);
    // All dirs are younger than the count-eviction horizon (the result
    // retention window): the count cap must not delete any of them early.
    await sweepArtifactRoot(root, 0, new Set(), 2, 1_600_000_000_000);
    expect(readdirSync(root).sort()).toEqual([
      "command-0", "command-1", "command-2", "command-3", "command-4",
    ]);
  });
});
